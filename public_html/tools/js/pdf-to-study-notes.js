pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';

        const fileInput = document.getElementById('file-input');
        const loading = document.getElementById('loading');
        const resultArea = document.getElementById('result-area');
        const notesContent = document.getElementById('notes-content');
        const dropZone = document.getElementById('drop-zone');

        fileInput.onchange = async (e) => {
            const file = e.target.files[0];
            if (!file) return;

            dropZone.style.display = 'none';
            loading.style.display = 'block';

            try {
                const arrayBuffer = await file.arrayBuffer();
                const pdf = await pdfjsLib.getDocument(arrayBuffer).promise;
                document.getElementById('doc-title').innerText = file.name.replace('.pdf', '') + " - Study Guide";
                
                let fullText = "";
                for (let i = 1; i <= pdf.numPages; i++) {
                    const page = await pdf.getPage(i);
                    const content = await page.getTextContent();
                    fullText += content.items.map(item => item.str).join(" ") + "\n";
                }

                generateNotes(fullText);
            } catch (err) {
                alert("Error processing PDF.");
                location.reload();
            }
        };

        function generateNotes(text) {
            loading.style.display = 'none';
            resultArea.style.display = 'block';

            // Simple heuristic to split into sections
            const lines = text.split(/(?<=[.!?])\s+|\n/);
            const chapters = [];
            let currentChapter = { title: "Introduction", points: [] };

            lines.forEach(line => {
                const trimmed = line.trim();
                if (trimmed.length < 10) return;

                // Detect potential headings (shorter, uppercase-ish)
                if (trimmed.length < 50 && (trimmed === trimmed.toUpperCase() || /^\d+\./.test(trimmed))) {
                    if (currentChapter.points.length > 0) chapters.push(currentChapter);
                    currentChapter = { title: trimmed, points: [] };
                } else if (trimmed.length > 60) {
                    currentChapter.points.push(trimmed);
                }
            });
            chapters.push(currentChapter);

            let html = "";
            chapters.slice(0, 8).forEach(c => {
                html += `
                    <div class="note-section">
                        <h3>${c.title}</h3>
                        ${c.points.slice(0, 4).map(p => `<div class="note-item">${p}</div>`).join('')}
                    </div>`;
            });

            notesContent.innerHTML = html;

            // Trigger Automatic Download
            setTimeout(() => { downloadPDF(chapters); }, 2000);
            document.getElementById('download-btn').onclick = () => downloadPDF(chapters);
        }

        function downloadPDF(chapters) {
            const { jsPDF } = window.jspdf;
            const doc = new jsPDF();
            let y = 20;

            doc.setFontSize(22);
            doc.setTextColor(250, 114, 32);
            doc.text("Academic Study Guide", 20, y);
            y += 15;

            doc.setFontSize(10);
            doc.setTextColor(150);
            doc.text("Generated by PDFIndi AI Engine", 20, y);
            y += 15;

            chapters.slice(0, 10).forEach(c => {
                if (y > 270) { doc.addPage(); y = 20; }
                doc.setFontSize(14);
                doc.setTextColor(0);
                doc.text(c.title, 20, y);
                y += 8;

                doc.setFontSize(10);
                doc.setTextColor(80);
                c.points.slice(0, 5).forEach(p => {
                    const splitText = doc.splitTextToSize("• " + p, 170);
                    doc.text(splitText, 25, y);
                    y += (splitText.length * 5) + 2;
                    if (y > 270) { doc.addPage(); y = 20; }
                });
                y += 5;
            });

            doc.save("pdfindi-study-notes.pdf");
        }