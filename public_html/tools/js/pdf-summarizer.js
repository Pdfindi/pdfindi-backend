pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';

        const dropZone = document.getElementById('drop-zone');
        const fileInput = document.getElementById('file-input');
        const loading = document.getElementById('loading');
        const result = document.getElementById('result');
        const summaryContent = document.getElementById('summary-content');
        const downloadBtn = document.getElementById('download-btn');

        dropZone.onclick = () => fileInput.click();
        fileInput.onchange = (e) => processFile(e.target.files[0]);

        async function processFile(file) {
            if (!file) return;
            dropZone.style.display = 'none';
            loading.style.display = 'block';

            try {
                const arrayBuffer = await file.arrayBuffer();
                const pdf = await pdfjsLib.getDocument(arrayBuffer).promise;
                let paragraphs = [];

                for (let i = 1; i <= pdf.numPages; i++) {
                    const page = await pdf.getPage(i);
                    const content = await page.getTextContent();
                    const text = content.items.map(item => item.str).join(" ");
                    paragraphs.push(...text.split(/(?<=[.!?])\s+/));
                }

                generateSummary(paragraphs);
            } catch (err) {
                alert("Error processing PDF.");
                location.reload();
            }
        }

        function generateSummary(paras) {
            loading.style.display = 'none';
            result.style.display = 'block';

            const keywords = ['summar', 'conclu', 'important', 'key', 'result', 'finding', 'essential', 'main', 'significan'];
            
            // Heuristic Summary: Pick paragraphs that are long enough and contain keywords
            let summary = paras.filter(p => {
                const lower = p.toLowerCase();
                return p.length > 50 && p.length < 500 && keywords.some(k => lower.includes(k));
            }).slice(0, 6);

            // Fallback: Just pick the first few paragraphs if no keywords found
            if (summary.length < 2) {
                summary = paras.filter(p => p.trim().length > 100).slice(0, 4);
            }

            const formattedSummary = summary.map(p => `• ${p.trim()}`).join('<br><br>');
            summaryContent.innerHTML = formattedSummary;

            // Trigger Automatic Download
            setTimeout(() => {
                downloadSummary(summary.join('\n\n'));
            }, 1500);

            downloadBtn.onclick = () => downloadSummary(summary.join('\n\n'));
        }

        function downloadSummary(text) {
            const { jsPDF } = window.jspdf;
            const doc = new jsPDF();
            
            doc.setFontSize(20);
            doc.text("PDF Summary (generated by PDFIndi)", 20, 20);
            
            doc.setFontSize(11);
            const splitText = doc.splitTextToSize(text, 170);
            doc.text(splitText, 20, 35);
            
            doc.save("pdfindi-summary.pdf");
        }