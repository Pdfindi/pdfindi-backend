const { jsPDF } = window.jspdf;
        const projectsContainer = document.getElementById('projects-container');
        const portfolioForm = document.getElementById('portfolio-form');

        function addProject() {
            const div = document.createElement('div');
            div.className = 'project-item';
            div.innerHTML = `
                <button type="button" class="remove-btn" onclick="this.parentElement.remove()">Remove</button>
                <div class="input-group">
                    <label>Project Name</label>
                    <input type="text" class="p-name" placeholder="E-commerce Platform" required>
                </div>
                <div class="input-group">
                    <label>Project Description</label>
                    <textarea class="p-desc" rows="2" placeholder="Describe what you built and the impact it had..."></textarea>
            </div>
            `;
            projectsContainer.appendChild(div);
        }

        // Initialize with one project
        addProject();

        portfolioForm.onsubmit = async (e) => {
            e.preventDefault();
            
            const doc = new jsPDF();
            const name = document.getElementById('name').value;
            const title = document.getElementById('title').value;
            const email = document.getElementById('email').value;
            const skills = document.getElementById('skills').value;

            // Header Section
            doc.setFillColor(250, 114, 32); // Brand Orange
            doc.rect(0, 0, 210, 40, 'F');
            
            doc.setTextColor(255, 255, 255);
            doc.setFontSize(24);
            doc.setFont('helvetica', 'bold');
            doc.text(name, 20, 20);
            
            doc.setFontSize(14);
            doc.setFont('helvetica', 'normal');
            doc.text(title, 20, 30);

            // Contact Info
            doc.setTextColor(50, 50, 50);
            doc.setFontSize(10);
            doc.text(`Email: ${email}`, 20, 50);
            
            // Skills
            doc.setFont('helvetica', 'bold');
            doc.setFontSize(14);
            doc.text("TECHNICAL EXPERTISE", 20, 65);
            doc.setDrawColor(250, 114, 32);
            doc.line(20, 68, 190, 68);
            
            doc.setFont('helvetica', 'normal');
            doc.setFontSize(11);
            doc.text(skills, 20, 75, { maxWidth: 170 });

            // Projects Section
            let y = 100;
            doc.setFont('helvetica', 'bold');
            doc.setFontSize(14);
            doc.text("FEATURED PROJECTS", 20, y);
            doc.line(20, y+3, 190, y+3);
            y += 12;

            const projects = document.querySelectorAll('.project-item');
            projects.forEach((item, index) => {
                if (y > 250) {
                    doc.addPage();
                    y = 20;
                }

                const pName = item.querySelector('.p-name').value;
                const pDesc = item.querySelector('.p-desc').value;

                doc.setFont('helvetica', 'bold');
                doc.setFontSize(12);
                doc.text(`${index + 1}. ${pName}`, 20, y);
                y += 6;
                
                doc.setFont('helvetica', 'normal');
                doc.setFontSize(10);
                const splitDesc = doc.splitTextToSize(pDesc, 160);
                doc.text(splitDesc, 25, y);
                y += (splitDesc.length * 5) + 8;
            });

            // Footer
            doc.setFontSize(8);
            doc.setTextColor(150, 150, 150);
            doc.text("Generated by PDFIndi Portfolio Creator", 105, 285, { align: 'center' });

            doc.save(`${name.replace(/\s+/g, '_')}_Portfolio.pdf`);
        };